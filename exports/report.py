# ── WATERMARK CANVAS ────────────────────────────────────────
class WatermarkCanvas(canvas.Canvas):
    """Draws a diagonal 'CleanSight' watermark + header/footer on every page."""

    def __init__(self, filename, **kwargs):
        super().__init__(filename, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self._draw_watermark()
            self._draw_header()
            self._draw_footer(self._pageNumber, total)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def _draw_watermark(self):
        self.saveState()
        self.setFont("Helvetica-Bold", 52)
        self.setFillColor(colors.HexColor("#185fa5"))
        self.setFillAlpha(0.04)
        self.translate(PAGE_W / 2, PAGE_H / 2)
        self.rotate(35)
        # Repeat across diagonal
        for y_off in [-260, -130, 0, 130, 260]:
            self.drawCentredString(0, y_off, "CleanSight")
        self.restoreState()

    def _draw_header(self):
        self.saveState()
        # Header bar
        self.setFillColor(C_ACCENT)
        self.rect(0, PAGE_H - 14*mm, PAGE_W, 14*mm, fill=1, stroke=0)
        # Logo text
        self.setFillColor(C_WHITE)
        self.setFont("Helvetica-Bold", 11)
        self.drawString(MARGIN, PAGE_H - 9*mm, "CleanSight")
        self.setFont("Helvetica", 9)
        self.drawString(MARGIN + 70, PAGE_H - 9*mm, "Data Quality Report")
        # Date on right
        date_str = datetime.now().strftime("%d %b %Y")
        self.drawRightString(PAGE_W - MARGIN, PAGE_H - 9*mm, date_str)
        self.restoreState()

    def _draw_footer(self, page_num, total):
        self.saveState()
        # Footer line
        self.setStrokeColor(C_BORDER)
        self.setLineWidth(0.5)
        self.line(MARGIN, 12*mm, PAGE_W - MARGIN, 12*mm)
        self.setFont("Helvetica", 8)
        self.setFillColor(C_TEXT3)
        self.drawString(MARGIN, 8*mm, "Generated by CleanSight AI Platform")
        self.drawRightString(PAGE_W - MARGIN, 8*mm, f"Page {page_num} of {total}")
        self.restoreState()


