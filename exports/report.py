# ── KPI CARDS ROW ────────────────────────────────────────────
def kpi_row(df, styles):
    """Returns a Table acting as a row of KPI cards."""
    rows     = len(df)
    cols     = len(df.columns)
    missing  = int(df.isnull().sum().sum())
    dupes    = int(df.duplicated().sum())
    num_cols = int(df.select_dtypes(include="number").shape[1])
    txt_cols = int(df.select_dtypes(include="object").shape[1])

    def card(val, label, color=C_TEXT):
        s = styles["kpi_val"]
        colored = ParagraphStyle(
            "kpi_val_c", parent=s, textColor=color
        )
        return [
            Paragraph(str(val), colored),
            Paragraph(label, styles["kpi_lbl"]),
        ]

    data = [[
        card(rows,     "Total Rows"),
        card(cols,     "Columns"),
        card(missing,  "Missing", C_WARN if missing > 0 else C_SUCCESS),
        card(dupes,    "Duplicates", C_DANGER if dupes > 0 else C_SUCCESS),
        card(num_cols, "Numeric", C_ACCENT),
        card(txt_cols, "Text"),
    ]]

    col_w = (PAGE_W - 2*MARGIN) / 6
    t = Table(data, colWidths=[col_w]*6, rowHeights=None)
    t.setStyle(TableStyle([
        ("BOX",           (0,0), (-1,-1), 0.5, C_BORDER),
        ("INNERGRID",     (0,0), (-1,-1), 0.5, C_BORDER),
        ("BACKGROUND",    (0,0), (-1,-1), C_CARD),
        ("TOPPADDING",    (0,0), (-1,-1), 10),
        ("BOTTOMPADDING", (0,0), (-1,-1), 10),
        ("LEFTPADDING",   (0,0), (-1,-1), 6),
        ("RIGHTPADDING",  (0,0), (-1,-1), 6),
        ("ROUNDEDCORNERS",(0,0), (-1,-1), 4),
        ("VALIGN",        (0,0), (-1,-1), "MIDDLE"),
    ]))
    return t


# ── QUALITY SCORE CARD ───────────────────────────────────────
def quality_card(score, styles):
    if score >= 80:
        grade, color, grade_text = "A", C_SUCCESS, "Excellent"
    elif score >= 60:
        grade, color, grade_text = "B", C_WARN, "Good"
    elif score >= 40:
        grade, color, grade_text = "C", C_WARN, "Fair"
    else:
        grade, color, grade_text = "D", C_DANGER, "Poor"

    score_style = ParagraphStyle(
        "qs", fontName="Helvetica-Bold", fontSize=22,
        textColor=color, leading=36, alignment=TA_CENTER
    )
    grade_style = ParagraphStyle(
        "qg", fontName="Helvetica-Bold", fontSize=11,
        textColor=color, leading=14, alignment=TA_CENTER
    )
    label_style = ParagraphStyle(
        "ql", fontName="Helvetica", fontSize=8,
        textColor=C_TEXT2, leading=12, alignment=TA_CENTER
    )

    inner = Table(
        [[
            Paragraph(f"{score}", score_style),
            
        ]],
        colWidths=[90],
    )
    inner.setStyle(TableStyle([
        ("VALIGN", (0,0), (-1,-1), "BOTTOM"),
        ("LEFTPADDING", (0,0), (-1,-1), 0),
        ("RIGHTPADDING", (0,0), (-1,-1), 0),
        ("TOPPADDING", (0,0), (-1,-1), 0),
        ("BOTTOMPADDING", (0,0), (-1,-1), 0),
    ]))

    card_data = [[
        inner,
        [
            Paragraph(grade_text, grade_style),
            Spacer(1, 3),
            Paragraph("Data Quality Score", label_style),
            Spacer(1, 3),
            Paragraph("AI-assessed dataset health", label_style),
        ],
    ]]

    avail_w = PAGE_W - 2*MARGIN
    t = Table(card_data, colWidths=[100, avail_w - 100])
    t.setStyle(TableStyle([
        ("BOX",           (0,0), (-1,-1), 0.5, C_BORDER),
        ("BACKGROUND",    (0,0), (-1,-1), C_CARD),
        ("TOPPADDING",    (0,0), (-1,-1), 14),
        ("BOTTOMPADDING", (0,0), (-1,-1), 14),
        ("LEFTPADDING",   (0,0), (-1,-1), 18),
        ("RIGHTPADDING",  (0,0), (-1,-1), 14),
        ("VALIGN",        (0,0), (-1,-1), "MIDDLE"),
        ("LINEAFTER",     (0,0), (0,-1),  0.5, C_BORDER),
    ]))
    return t


